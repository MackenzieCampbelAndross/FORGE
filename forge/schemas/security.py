"""Pydantic schemas for STRIDE threat modeling and security analysis."""

from enum import Enum

from pydantic import BaseModel, Field


class STRIDECategory(str, Enum):
    SPOOFING = "SPOOFING"
    TAMPERING = "TAMPERING"
    REPUDIATION = "REPUDIATION"
    INFORMATION_DISCLOSURE = "INFORMATION_DISCLOSURE"
    DENIAL_OF_SERVICE = "DENIAL_OF_SERVICE"
    ELEVATION_OF_PRIVILEGE = "ELEVATION_OF_PRIVILEGE"


class SeverityLevel(str, Enum):
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class LikelihoodLevel(str, Enum):
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class ImpactLevel(str, Enum):
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class SecurityMitigation(BaseModel):
    """Mitigation control for a specific threat."""

    mitigation_id: str = Field(..., description="Unique ID, e.g. MIT-001")
    description: str = Field(..., min_length=10)
    owasp_mapping: str | None = Field(
        default=None, description="e.g. OWASP A01:2021-Broken Access Control"
    )
    verification_method: str = Field(default="Automated security scan / unit tests")


class ThreatItem(BaseModel):
    """Structured STRIDE threat assessment item."""

    threat_id: str = Field(..., description="Unique ID, e.g. THR-001")
    category: STRIDECategory = Field(...)
    affected_component_id: str = Field(..., description="Target component ID")
    attack_scenario: str = Field(..., min_length=15, description="Realistic attack scenario")
    likelihood: LikelihoodLevel = Field(default=LikelihoodLevel.MEDIUM)
    impact: ImpactLevel = Field(default=ImpactLevel.HIGH)
    severity: SeverityLevel = Field(default=SeverityLevel.HIGH)
    risk_score: float = Field(
        default=0.0, ge=0.0, le=10.0, description="Computed deterministic risk score (0-10)"
    )
    mitigation: SecurityMitigation = Field(...)
    residual_risk: SeverityLevel = Field(default=SeverityLevel.LOW)
    owasp_reference: str | None = Field(default=None)


class AttackSurface(BaseModel):
    """Identified system boundary exposed to external or untrusted entities."""

    surface_id: str = Field(...)
    name: str = Field(...)
    exposure_type: str = Field(
        default="Public Internet", description="e.g. Public, Internal VPC, Admin"
    )
    description: str = Field(default="")
    protected_by: list[str] = Field(
        default_factory=list, description="Controls protecting this surface"
    )


class ThreatModel(BaseModel):
    """STRIDE Threat Model generated by the Security Architect."""

    threat_model_id: str = Field(...)
    project_id: str = Field(...)
    threats: list[ThreatItem] = Field(default_factory=list)
    attack_surfaces: list[AttackSurface] = Field(default_factory=list)
    overall_risk_posture: SeverityLevel = Field(default=SeverityLevel.MEDIUM)
    recommendations: list[str] = Field(default_factory=list)
